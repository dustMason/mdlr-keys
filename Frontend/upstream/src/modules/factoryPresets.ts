function preset(
  moduleKind: number,
  moduleSlug: string,
  name: string,
  params: Record<number, number>,
): ModulePresetDefinition {
  return {
    id: `factory:${moduleSlug}:${slugify(name)}`,
    name,
    payload: {
      version: 1,
      moduleKind,
      moduleSlug,
      params: Object.fromEntries(
        Object.entries(params).map(([paramId, value]) => [paramId, value]),
      ),
    },
  };
}

function slugify(value: string) {
  return value.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
}
